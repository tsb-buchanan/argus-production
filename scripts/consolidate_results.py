#!/usr/bin/env python3
"""consolidate_results.py: session-2 task 5 - machine-readable results index + RESULTS.md.

Two outputs, both generated from source artifacts with NO hand-written numbers
(same regenerate-from-source discipline as the Layer-1 memo):

  1. results/run_index.{csv,json} - one row per committed run card: the flat
     table that answers "what has actually been run" without opening DuckDB.
  2. results/RESULTS.md - the human-readable Phase 0 results index. Every
     number in it is read from results/*/*.json|csv at generation time; the
     prose is templated, the values are not.

Usage:
  python3 scripts/consolidate_results.py
"""

import csv
import json
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
RES = REPO / "results"

FIELDS = ["candidate", "case", "dimensionality", "condition", "eta", "alpha_deg",
          "CL", "CD", "CD_counts", "CD_pressure", "CD_viscous", "Cm",
          "cells", "yplus_max", "max_skewness", "max_non_orthogonality",
          "iterations", "converged", "trim_target_CL", "trim_alpha_deg",
          "trim_converged", "aft_attached", "geometry", "geometry_sha256_short",
          "git_commit_short", "openfoam_version", "core_hours", "machine", "date"]


def row_from_card(card):
    c, m, r = card["case"], card["mesh"], card["results"]
    t = card.get("trim") or {}
    att = r.get("aft_attachment")
    return {
        "candidate": card["candidate"], "case": c["path"],
        "dimensionality": c["dimensionality"], "condition": c["condition"],
        "eta": c.get("eta"), "alpha_deg": card["conditions"]["alpha_deg"],
        "CL": r["CL"], "CD": r["CD"], "CD_counts": round(r["CD"] * 1e4, 3),
        "CD_pressure": r["CD_pressure"], "CD_viscous": r["CD_viscous"], "Cm": r["Cm"],
        "cells": m["cells"], "yplus_max": m["yplus"]["max"],
        "max_skewness": m["max_skewness"],
        "max_non_orthogonality": m["max_non_orthogonality"],
        "iterations": card["convergence"]["iterations"],
        "converged": card["convergence"]["converged"],
        "trim_target_CL": t.get("target_CL"), "trim_alpha_deg": t.get("alpha_trim_deg"),
        "trim_converged": t.get("converged"),
        "aft_attached": (att["upper"]["attached"] and att["lower"]["attached"])
                        if att else None,
        "geometry": card["geometry"]["file"],
        "geometry_sha256_short": card["geometry"]["sha256"][:12],
        "git_commit_short": card["provenance"]["git_commit"][:8],
        "openfoam_version": card["provenance"]["openfoam_version"],
        "core_hours": round(card["cost"]["core_hours"], 3),
        "machine": card["cost"]["machine"], "date": card["provenance"]["date"],
    }


def build_index():
    rows = [row_from_card(json.loads(p.read_text()))
            for p in sorted(REPO.glob("cases/*/*/run_card.json"))]
    rows.sort(key=lambda r: (r["candidate"], r["case"]))
    with (RES / "run_index.csv").open("w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=FIELDS)
        w.writeheader(); w.writerows(rows)
    (RES / "run_index.json").write_text(json.dumps(rows, indent=2) + "\n")
    return rows


def load(rel, default=None):
    p = RES / rel
    if not p.exists():
        return default
    if p.suffix == ".json":
        return json.loads(p.read_text())
    with p.open() as f:
        return list(csv.DictReader(f))


def fmt_counts(x):
    return f"{float(x) * 1e4:.2f}"


def results_md(rows):
    """Every number below is read from an artifact; nothing is transcribed."""
    L = []
    A = L.append
    total_ch = sum(r["core_hours"] for r in rows)
    n2d = sum(1 for r in rows if r["dimensionality"] == "2D")

    A("# ARGUS Phase 0 results index")
    A("")
    A("Generated by `scripts/consolidate_results.py` from the committed run cards and "
      "`results/` artifacts. Do not hand-edit: regenerate. Every number here is read "
      "from source at generation time.")
    A("")
    A(f"Runs on record: {len(rows)} ({n2d} 2D). Total {total_ch:.1f} core-hours. "
      f"Machine(s): {', '.join(sorted({r['machine'] for r in rows}))}. "
      f"Solver: {', '.join(sorted({r['openfoam_version'] for r in rows}))}.")
    A("")

    # --- 1. Layer 1 (TMR NACA 0012)
    A("## 1. D012 Layer 1: solver verification vs the NASA TMR NACA 0012 (ACCEPTED)")
    rich = load("tmr_naca0012/ogrid_richardson.json")
    tmr = [r for r in rows if r["candidate"] == "tmr_naca0012"]
    if tmr:
        A("")
        A("| case | alpha | cells | cl | cd (counts) | y+ max |")
        A("|---|---|---|---|---|---|")
        for r in sorted(tmr, key=lambda r: (r["alpha_deg"], r["cells"])):
            A(f"| {Path(r['case']).name} | {r['alpha_deg']:g} | {r['cells']} | "
              f"{r['CL']:.5f} | {r['CD_counts']:.2f} | {r['yplus_max']:.2f} |")
    if rich:
        band = rich.get("band_897_reference", {})
        for key, label in (("alpha0", "alpha 0"), ("alpha10", "alpha 10")):
            blk = rich.get("richardson", {}).get(key)
            if not blk:
                continue
            A("")
            seq = blk["cd_sequence_counts"]
            inc = blk["cd_increments_counts"]
            A(f"- {label}: cd sequence (counts) "
              f"{' -> '.join(f'{v:.2f}' for v in seq)} over levels "
              f"{'/'.join(blk['levels'])}; increments "
              f"{', '.join(f'{v:+.2f}' for v in inc)}.")
            cd = blk.get("cd", {})
            if cd.get("gci_fine_pct"):
                A(f"  Richardson cd = {cd['extrapolated'] * 1e4:.2f} counts "
                  f"(p = {cd['p_observed']:.2f}, GCI {cd['gci_fine_pct']:.2f}%).")
            else:
                A(f"  Richardson not licensed: {cd.get('note', 'n/a')}.")
            for q, ql in (("cdp", "pressure"), ("cdv", "viscous")):
                g = blk.get(q, {})
                if g.get("gci_fine_pct"):
                    A(f"  cd_{ql}: p = {g['p_observed']:.2f}, "
                      f"GCI {g['gci_fine_pct']:.2f}%.")
            akey = key.replace("alpha", "") + ".0"
            vals = [v[1] for code, d in band.items() if (v := d.get(akey))]
            if vals:
                A(f"  TMR reference band at {label}: "
                  f"{min(vals) * 1e4:.2f} to {max(vals) * 1e4:.2f} counts "
                  f"({', '.join(sorted(band))}).")
        a2 = rich.get("a2_diagnostic", {})
        if a2:
            A("")
            A(f"- D013 A2 alpha-0 symmetry diagnostic (|cl| < 1e-3): "
              f"{sum(1 for v in a2.values() if v['pass'])}/{len(a2)} levels pass "
              f"(max |cl| {max(abs(v['cl_alpha0']) for v in a2.values()):.2e}). "
              f"Necessary but NOT sufficient for laminarization (D018.3).")
    A("")
    A("Acceptance basis and caveats: D013 + D013 A1 mini-amendment (alpha 0 uses "
      "finest-value-plus-decomposition, not Richardson) and D018 standing policies.")
    A("")

    # --- 2. EET grid convergence
    A("## 2. EET 2D grid convergence, Condition CR (D012 ladder)")
    fam = load("eet2d_cr/grid_family.csv")
    grich = load("eet2d_cr/grid_richardson.json")
    if fam:
        A("")
        A("| level | cells | cl | cd (counts) | cd_p | cd_v | y+ max | checkMesh |")
        A("|---|---|---|---|---|---|---|---|")
        for r in fam:
            A(f"| {r['level']} | {r['cells']} | {float(r['cl']):.6f} | "
              f"{fmt_counts(r['cd'])} | {fmt_counts(r['cd_pressure'])} | "
              f"{fmt_counts(r['cd_viscous'])} | {float(r['yplus_max']):.2f} | "
              f"{'PASS' if r['checkMesh_pass'] in ('True', True) else 'FLAGGED'} |")
    if grich:
        A("")
        for q in ("cl", "cd", "cdp", "cdv"):
            g = grich.get(q, {})
            if "gci_fine_pct" in g:
                A(f"- `{q}`: observed order p = {g['p_observed']:.2f}, "
                  f"GCI(fine) = {g['gci_fine_pct']:.2f}%, "
                  f"extrapolated = {g['extrapolated']:.6f}.")
            else:
                A(f"- `{q}`: {g.get('note', 'n/a')} (fine value {g.get('value_fine')}).")
    A("")

    # --- 3. Task 3 fixed-cl deltas (headline)
    A("## 3. HEADLINE: fixed-cl morphed-section deltas (D019 + amendment 1)")
    td = load("eet2d_cr/trim_deltas.json")
    if td:
        A("")
        A("Morphed minus baseline at matched sectional cl (DSO .lod targets), matched "
          "fine O-grids, Condition CR. True wind axes per D019 amendment 1.")
        A("")
        A("| eta | target cl | alpha_base | alpha_morph | d_alpha | cd_base (cts) | "
          "cd_morph (cts) | dcd | dcd_p | dcd_v | dcm | attached |")
        A("|---|---|---|---|---|---|---|---|---|---|---|---|")
        for r in td:
            att = "yes" if (r["aft_attached_baseline"] and r["aft_attached_morphed"]) else "NO"
            A(f"| {r['eta']:.2f} | {r['target_cl']:.4f} | {r['alpha_baseline_deg']:+.3f} | "
              f"{r['alpha_morphed_deg']:+.3f} | {r['dalpha_deg']:+.3f} | "
              f"{r['cd_baseline_counts']:.2f} | {r['cd_morphed_counts']:.2f} | "
              f"{r['dcd_counts']:+.2f} | {r['dcd_pressure_counts']:+.2f} | "
              f"{r['dcd_viscous_counts']:+.2f} | {r['dcm']:+.5f} | {att} |")
        worst = max(abs(r["dcd_counts"]) for r in td)
        A("")
        A(f"Bound: |dcd| <= {worst:.2f} counts across stations, attached at every station, "
          f"against the DSO induced-drag gain of "
          f"{(0.009167626874 - 0.008838448645) * 1e4:.2f} counts "
          f"(registry `dso_strict` CDi values).")
        A("")
        A("Figure: `results/eet2d_cr/trim_deltas.png`.")
    A("")

    # --- 4. XFOIL code-to-code
    A("## 4. XFOIL cross-check (CODE-TO-CODE ONLY)")
    xc = load("eet2d_cr/xfoil/crosscheck_summary.json")
    if xc:
        A("")
        A(f"{xc['label']}")
        A("")
        s = xc.get("lift_slope_per_deg_fit_-2_to_4", {})
        a0 = xc.get("alpha_at_cl0_deg", {})
        A(f"- Lift slope per deg (fit -2..4): RANS {s.get('rans')}, "
          f"XFOIL forced-xtr {s.get('xfoil_forced')}, XFOIL free {s.get('xfoil_free')}.")
        A(f"- alpha at cl = 0 (deg): RANS {a0.get('rans')}, "
          f"XFOIL forced-xtr {a0.get('xfoil_forced')}, XFOIL free {a0.get('xfoil_free')}.")
        h = xc.get("headline_at_matched_cl")
        if h:
            b = h.get("operating_band")
            if b:
                A(f"- At matched cl in the OPERATING BAND (cl {b['cl_range'][0]}-"
                  f"{b['cl_range'][1]}, {b['n_points']} points), XFOIL(forced) minus RANS: "
                  f"{', '.join(f'{v:+.2f}' for v in b['dcd_counts'])} counts, i.e. "
                  f"|dcd| <= {b['max_abs_dcd_counts']:.2f} counts.")
            A(f"- Over the full compared range ({h['n_points']} points): "
              f"{h['dcd_counts_min']:+.2f} to {h['dcd_counts_max']:+.2f} counts "
              f"(mean {h['dcd_counts_mean']:+.2f}); the codes separate above "
              f"cl ~0.6 as the aft adverse gradient strengthens.")
        ps = xc.get("xfoil_setup", {}).get("panel_sensitivity", {})
        if ps:
            A(f"- XFOIL panel sensitivity (N 200-360): cd spread <= "
              f"{max(v['cd_spread_counts'] for v in ps.values()):.2f} counts, "
              f"cl spread <= {max(v['cl_spread'] for v in ps.values()):.4f}.")
        A("")
        A("Figure: `results/eet2d_cr/xfoil/xfoil_crosscheck.png`. "
          "No experimental data is involved; this is agreement between two codes only.")
    A("")

    # --- 5. DSO reference
    A("## 5. DSO reference (Zheng package, gated)")
    A("")
    A("Strip loads and headers under `results/dso_reference/`; package provenance and "
      "checksums in `registry/candidates.yaml` (`dso_package`). Gate verdict: D017.")
    A("")

    # --- 6. artifact manifest
    A("## 6. Artifacts")
    A("")
    A("| file | bytes |")
    A("|---|---|")
    for p in sorted(RES.rglob("*")):
        if p.is_file() and p.suffix in (".csv", ".json", ".png", ".md", ".txt"):
            A(f"| `{p.relative_to(REPO)}` | {p.stat().st_size} |")
    A("")
    A("Derived query layer: `results/argus.duckdb` (rebuild with "
      "`scripts/build_results_db.py`; not a store of record).")
    return "\n".join(L) + "\n"


def main():
    rows = build_index()
    (RES / "RESULTS.md").write_text(results_md(rows))
    print(f"run_index: {len(rows)} cards -> results/run_index.csv / .json")
    print(f"RESULTS.md: {(RES / 'RESULTS.md').stat().st_size} bytes")


if __name__ == "__main__":
    main()
